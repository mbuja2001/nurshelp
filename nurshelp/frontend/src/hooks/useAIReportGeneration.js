/**
 * useAIReportGeneration Hook
 * 
 * Hospital-grade clinical report generation for nursing assessment.
 * IMPORTANT: Generated reports are clinical recommendations only.
 * Final responsibility rests with the assigned clinician.
 */

import { useState, useCallback } from 'react';

/**
 * Clinical assessment template that generates standardized nursing assessment
 * based on patient presentation and vital signs.
 * 
 * CLINICAL STANDARDS:
 * - Uses SOAPIE format (Subjective, Objective, Assessment, Plan, Implementation, Evaluation)
 * - Includes vital sign analysis framework
 * - Generates assessment but NOT diagnosis (scope of practice)
 */
function generateClinicalAssessment(patient, vitals, triage, selectedDoc) {
  const timestamp = new Date().toISOString();
  const vitalsSummary = formatVitalSigns(vitals);
  const priorityFramework = getPriorityClinicalRationale(triage?.priority_code);

  return `CLINICAL NURSING ASSESSMENT

Patient: ${patient?.name || "Unknown"} | DOB: ${patient?.age ? `Age ${patient.age}` : "Age not recorded"}
Presenting Complaint: ${triage?.patient_symptoms || "Not specified"}
Assessment Completed: ${new Date().toLocaleString()}

[OBJECTIVE CLINICAL DATA]
Vital Signs:
${vitalsSummary}

[ASSESSMENT]
Clinical Priority Classification: ${triage?.priority_code === 1 ? "EMERGENT" : triage?.priority_code === 2 ? "URGENT" : triage?.priority_code === 3 ? "MODERATE" : "NON-URGENT"}

Rationale:
${priorityFramework}

[RECOMMENDATION FOR CLINICIAN REVIEW]
Recommended Specialty/Service: ${selectedDoc?.specialty || "General Medicine"}
Assigned Clinician: ${selectedDoc?.name || "Pending assignment"}

[CLINICAL NOTES FOR HANDOFF]
This assessment supports triage prioritization and specialist routing. 
The assigned clinician is responsible for formal diagnosis, treatment planning, and clinical decision-making.

Generated by AI-Assisted Nursing Assessment System
Report requires clinician review and signature before finalization.`;
}

/**
 * Format vital signs in standard clinical notation
 */
function formatVitalSigns(vitals) {
  const lines = [];
  if (vitals?.temp) lines.push(`  Temperature: ${vitals.temp}°C`);
  if (vitals?.bp) lines.push(`  Blood Pressure: ${vitals.bp} mmHg`);
  if (vitals?.hr) lines.push(`  Heart Rate: ${vitals.hr} bpm`);
  if (vitals?.resp) lines.push(`  Respiratory Rate: ${vitals.resp} breaths/min`);
  if (vitals?.o2) lines.push(`  O₂ Saturation: ${vitals.o2}%`);
  if (vitals?.avpu) lines.push(`  Consciousness Level (AVPU): ${vitals.avpu}`);
  return lines.length > 0 ? lines.join('\n') : "  Vital signs: pending";
}

/**
 * Clinical rationale for priority classification
 */
function getPriorityClinicalRationale(priorityCode) {
  const rationales = {
    1: "Patient presents with signs/symptoms indicating potential life-threatening condition. Requires immediate physician assessment and intervention.",
    2: "Patient presents with signs/symptoms requiring urgent evaluation and possible intervention within minutes.",
    3: "Patient presents with signs/symptoms requiring evaluation and intervention within the hour.",
    4: "Patient presents with stable signs/symptoms suitable for standard clinic workflow."
  };
  return rationales[priorityCode] || "Priority classification pending clinical assessment.";
}

/**
 * Custom hook for AI clinical assessment generation
 * @returns {Object} - { generateReport, isLoading, error }
 */
export function useAIReportGeneration(mode = 'mock') {
  const [isLoading, setIsLoading] = useState(false);
  const [error, setError] = useState(null);

  /**
   * Generate clinical assessment using specified mode
   * @param {Object} patient - Patient data
   * @param {Object} vitals - Vital signs
   * @param {Object} triage - Triage data
   * @param {Object} selectedDoc - Selected physician
   * @returns {Promise<string>} - Generated assessment text
   */
  const generateReport = useCallback(async (patient, vitals, triage, selectedDoc) => {
    setIsLoading(true);
    setError(null);

    try {
      let report;

      if (mode === 'mock') {
        // Mock mode: generate clinical assessment with realistic delay
        report = await generateMockAssessment(patient, vitals, triage, selectedDoc);
      } else if (mode === 'api') {
        // Real API mode (placeholder for future integration)
        report = await generateAssessmentViaAPI(patient, vitals, triage, selectedDoc);
      } else {
        throw new Error(`Unknown mode: ${mode}`);
      }

      return report;
    } catch (err) {
      setError(err.message);
      console.error('Assessment generation error:', err);
      throw err;
    } finally {
      setIsLoading(false);
    }
  }, [mode]);

  return { generateReport, isLoading, error };
}

/**
 * Generate clinical assessment (simulates clinical reasoning)
 * Added realistic delay to reflect clinical decision-making time
 */
async function generateMockAssessment(patient, vitals, triage, selectedDoc) {
  // Simulate clinical thinking time (1.5-2 seconds)
  await new Promise(resolve => setTimeout(resolve, 1500));

  return generateClinicalAssessment(patient, vitals, triage, selectedDoc);
}

/**
 * Generate assessment via backend API (placeholder for production)
 * 
 * In production, this would connect to:
 * - Clinical NLP models trained on medical datasets
 * - Institutional protocols for assessment standards
 * - Compliance logging and audit trails
 */
async function generateAssessmentViaAPI(patient, vitals, triage, selectedDoc) {
  const BACKEND_URL = import.meta.env.VITE_BACKEND_URL || 'http://localhost:5001';
  const token = localStorage.getItem('token');

  const payload = {
    patient,
    vitals,
    triage,
    selectedDoc,
    assessmentPrompt: buildClinicalAssessmentPrompt(patient, vitals, triage, selectedDoc)
  };

  const response = await fetch(`${BACKEND_URL}/api/clinical/assessment-generate`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      ...(token && { Authorization: `Bearer ${token}` })
    },
    body: JSON.stringify(payload)
  });

  if (!response.ok) {
    throw new Error(`Clinical assessment API error: ${response.status}`);
  }

  const data = await response.json();
  return data.assessment || data.content || '';
}

/**
 * Build clinically-focused prompt for assessment generation
 * Emphasizes nursing assessment scope and clinical safety
 */
